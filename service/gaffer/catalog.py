"""What a light can do, read from the generated model table.

Nothing here is hand-maintained. ``data/models.json`` and ``data/gels.json`` are
the capability and gel tables generated by the ha-godox-mesh project from the
Godox app's own catalogue; ``data/gel-colours.json`` is Godox's published gel
swatch list, which gives each gel its true colour. Built-in effect parameters
come from the library's ``FX_V3`` table.

The Godox mesh protocol is the same across the range; models differ only in
this metadata. So a light gets the right studio from data alone: look up its
``radioId``, and every tab, range and option follows from the row.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from functools import lru_cache
from typing import Any, Literal

from godox_mesh_bt.protocol import FX_V3, FX_V3_DEFAULTS, FX_V3_SPEED_MAX

from .paths import PACKAGE_DATA

_CAPS_PATH = PACKAGE_DATA / "models.json"
_GELS_PATH = PACKAGE_DATA / "gels.json"
_CHIP_HEX_PATH = PACKAGE_DATA / "gel-colours.json"

#: The gel catalogue used to emulate gels on a light that has no gel mode.
EMULATION_GEL_VERSION = 2

Kind = Literal["rgb", "colour", "bicolour", "daylight", "unsupported"]

KIND_LABELS: dict[str, str] = {
    "rgb": "RGB + white",
    "colour": "Colour",
    "bicolour": "Bi-colour",
    "daylight": "Daylight",
    "unsupported": "Not supported",
}


@dataclass(frozen=True, slots=True)
class BuiltinEffect:
    symbol: int
    name: str
    params: tuple[dict[str, Any], ...]
    #: Highest speed the effect takes; 0 means one fixed speed.
    speed_max: int = 0


@dataclass(frozen=True, slots=True)
class ModelCaps:
    radio_id: str
    name: str
    chip: str
    min_kelvin: int
    max_kelvin: int
    gm_min: int
    gm_max: int
    modes: tuple[str, ...]
    effect_version: int
    effects: tuple[BuiltinEffect, ...]
    fan_modes: tuple[dict[str, Any], ...]
    color_chip_version: int
    rgb_display: int
    rgb_channels: tuple[str, ...]
    battery: bool
    smoothness_modes: tuple[dict[str, Any], ...] = field(default=())
    control_modes: tuple[dict[str, Any], ...] = field(default=())
    frequencies: tuple[dict[str, Any], ...] = field(default=())
    brightness_steps: int = 100
    note: str = ""
    known: bool = True

    # -- what kind of light ---------------------------------------------------

    @property
    def has_white(self) -> bool:
        """A white (colour-temperature) mode, fixed or tunable."""
        return "cct" in self.modes and self.max_kelvin > 0

    @property
    def is_daylight(self) -> bool:
        """White at one fixed colour temperature: brightness is the only control."""
        return self.has_white and self.min_kelvin == self.max_kelvin

    @property
    def has_colour(self) -> bool:
        return "hsi" in self.modes

    @property
    def has_channels(self) -> bool:
        """Direct red/green/blue/white channel control."""
        return "rgb" in self.modes and "RGBW" in self.rgb_channels

    @property
    def has_tint(self) -> bool:
        return self.gm_min < 0 < self.gm_max

    @property
    def kind(self) -> Kind:
        if self.has_colour:
            return "rgb" if self.has_white else "colour"
        if self.has_white:
            return "daylight" if self.is_daylight else "bicolour"
        return "unsupported"

    @property
    def gel_support(self) -> str | None:
        """How gels reach this light: its own gel mode, recreated in colour, or as white."""
        if "color_chip" in self.modes and gels(self.color_chip_version):
            return "native"
        if self.has_colour:
            return "emulated"
        if self.has_white and (not self.is_daylight or self.has_tint):
            return "white"
        return None

    @property
    def effect_symbols(self) -> frozenset[int]:
        return frozenset(e.symbol for e in self.effects)

    @property
    def features(self) -> dict[str, Any]:
        """The switches the UI reads to decide which tabs and controls to show."""
        return {
            "white": self.has_white,
            "daylight": self.is_daylight,
            "colour": self.has_colour,
            "channels": self.has_channels,
            "tint": self.has_tint,
            "gels": self.gel_support,
            "builtin_effects": len(self.effects),
            "fan": bool(self.fan_modes),
            "battery": self.battery,
            "smoothness": bool(self.smoothness_modes),
            "control_modes": bool(self.control_modes),
        }

    def gel_table(self) -> tuple[dict[str, Any], ...]:
        """Every gel this light can show, each tagged with how it gets there."""
        from .gel_emulation import emulation_kind, fits_white_light

        support = self.gel_support
        if support is None:
            return ()
        if support == "native":
            return tuple({**g, "how": "native"} for g in gels(self.color_chip_version))
        if support == "emulated":
            return tuple({**g, "how": emulation_kind(g["hex"])} for g in gels(EMULATION_GEL_VERSION))
        return tuple({**g, "how": "white"} for g in gels(EMULATION_GEL_VERSION) if fits_white_light(g["hex"], self))

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data.update(
            has_tint=self.has_tint,
            kind=self.kind,
            kind_label=KIND_LABELS[self.kind],
            features=self.features,
        )
        return data


# Ranges for the V3 effect parameters. The library knows each effect's parameter
# names and the vendor app's defaults, but not their limits; these are inferred
# from the defaults and flagged so the UI can say so.
_V3_PARAM_SPECS: dict[str, dict[str, Any]] = {
    "speed": {"label": "Speed", "kind": "number", "min": 0, "max": FX_V3_SPEED_MAX},
    "sat": {"label": "Saturation", "kind": "number", "min": 0, "max": 100, "unit": "%"},
    "trigger": {"label": "Manual trigger", "kind": "bool", "inferred": True},
    "mode": {"label": "Mode", "kind": "number", "min": 0, "max": 3, "inferred": True},
    "option": {
        "label": "Colour source",
        "kind": "choice",
        "options": [{"value": 0, "label": "White (CCT)"}, {"value": 1, "label": "Colour (hue)"}],
    },
    "option_value": {"label": "Kelvin / hue", "kind": "option_value"},
    "gm": {"label": "Tint / saturation", "kind": "number", "min": 0, "max": 100, "inferred": True},
    "frequency": {"label": "Frequency", "kind": "number", "min": 0, "max": 100, "inferred": True},
    "twinkling": {"label": "Twinkle", "kind": "number", "min": 0, "max": 20, "inferred": True},
    "temperature": {"label": "Colour temperature", "kind": "kelvin100"},
    "light_dark": {"label": "Light / dark", "kind": "number", "min": 0, "max": 100, "inferred": True},
    "ember": {"label": "Embers", "kind": "number", "min": 0, "max": 100, "inferred": True},
    "color": {"label": "Colour scheme", "kind": "number", "min": 0, "max": 3, "inferred": True},
    "gear": {"label": "Gear", "kind": "number", "min": 0, "max": 3, "inferred": True},
    "tone_mode": {"label": "Tone", "kind": "number", "min": 0, "max": 3, "inferred": True},
}


def v3_param_schema(symbol: int) -> tuple[dict[str, Any], ...]:
    """Return the UI schema for one V3 effect's parameters, in wire order."""
    if symbol not in FX_V3:
        return ()
    _, names = FX_V3[symbol]
    return tuple(
        {"key": name, "default": FX_V3_DEFAULTS[name], **_V3_PARAM_SPECS.get(name, {"kind": "number", "min": 0, "max": 255})}
        for name in names
    )


@lru_cache(maxsize=1)
def _caps_table() -> dict[str, Any]:
    raw = json.loads(_CAPS_PATH.read_text(encoding="utf-8"))
    # Underscore-prefixed keys carry provenance, not models.
    return {k.upper(): v for k, v in raw.items() if not k.startswith("_")}


def _effects(row: dict[str, Any]) -> tuple[BuiltinEffect, ...]:
    version = int(row.get("effect_version", 0))
    effects = []
    for e in sorted(row.get("effects") or (), key=lambda e: e["symbol"]):
        if version == 1:
            # A newer-generation model can only be sent effects the library has
            # a V3 frame for; offering one it cannot build would fail on use.
            if e["symbol"] not in FX_V3:
                continue
            effects.append(BuiltinEffect(e["symbol"], e["name"], v3_param_schema(e["symbol"]), FX_V3_SPEED_MAX))
        else:
            # Older effects step through ``gears`` speeds; the app's slider runs 0..gears-1.
            effects.append(BuiltinEffect(e["symbol"], e["name"], (), max(0, int(e.get("gears", 1)) - 1)))
    return tuple(effects)


def _unknown(radio_id: str) -> ModelCaps:
    """A light whose model id is missing or not in the table.

    Bi-colour 2800-6500 K is what most of the range does and is safe on all of
    it: a colour command to a white-only light would be ignored, but white is
    understood everywhere. Built-in effects are left out because their symbols
    mean different things on different models.
    """
    label = f"Godox light ({radio_id})" if radio_id else "Godox light"
    return ModelCaps(
        radio_id=radio_id, name=label, chip="", min_kelvin=2800, max_kelvin=6500, gm_min=0, gm_max=0,
        modes=("cct",), effect_version=0, effects=(), fan_modes=(), color_chip_version=0, rgb_display=0,
        rgb_channels=(), battery=False, known=False,
    )


@lru_cache(maxsize=256)
def model_caps(radio_id: str | None) -> ModelCaps:
    """One model's capabilities, or a safe default for a model the table does not know."""
    key = (radio_id or "").upper()
    row = _caps_table().get(key)
    if row is None:
        return _unknown(key)
    return ModelCaps(
        radio_id=key,
        name=row["name"],
        chip=row.get("chip") or "",
        min_kelvin=row["min_kelvin"],
        max_kelvin=row["max_kelvin"],
        gm_min=row.get("gm_min", 0),
        gm_max=row.get("gm_max", 0),
        modes=tuple(row.get("modes") or ()),
        effect_version=int(row.get("effect_version", 0)),
        effects=_effects(row),
        fan_modes=tuple(row.get("fan_modes") or ()),
        color_chip_version=int(row.get("color_chip_version", 0)),
        rgb_display=int(row.get("rgb_display", 0)),
        rgb_channels=tuple(row.get("rgb_channels") or ()),
        battery=bool(row.get("battery")),
        smoothness_modes=tuple(row.get("smoothness_modes") or ()),
        control_modes=tuple(row.get("control_modes") or ()),
        frequencies=tuple(row.get("frequencies") or ()),
        brightness_steps=int(row.get("brightness_steps", 100)),
        note=str(row.get("note") or ""),
    )


@lru_cache(maxsize=1)
def models_index() -> tuple[dict[str, str], ...]:
    """Every known model, by name: for a model picker."""
    rows = []
    for radio_id in _caps_table():
        caps = model_caps(radio_id)
        rows.append({"radio_id": radio_id, "name": caps.name, "kind": caps.kind, "kind_label": KIND_LABELS[caps.kind]})
    return tuple(sorted(rows, key=lambda r: r["name"].lower()))


@lru_cache(maxsize=8)
def gels(version: int) -> tuple[dict[str, Any], ...]:
    """Every gel a model of this colour-chip version accepts, with its true colour."""
    entries = json.loads(_GELS_PATH.read_text(encoding="utf-8"))["versions"].get(str(version), [])
    chips = json.loads(_CHIP_HEX_PATH.read_text(encoding="utf-8"))["chips"]
    hex_by_label: dict[str, str] = {}
    for chip in chips:
        if chip["colorChipVersion"] != version:
            continue
        parts = [chip["brandSeries"], chip["referenceType"], chip["colorNum"]]
        hex_by_label[" ".join(p for p in parts if p)] = chip["hexString"].lower()
    result = []
    for entry in entries:
        label = entry["label"]
        series, _, rest = label.partition(" ")
        family = rest.rsplit(" ", 1)[0] if " " in rest else ""
        result.append(
            {
                **entry,
                "version": version,
                "series": series,
                "family": family,
                "hex": hex_by_label.get(label, "#808080"),
            }
        )
    return tuple(result)
