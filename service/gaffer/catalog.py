"""What a light can do, read from the generated model table.

Nothing here is hand-maintained. ``data/models.json`` and ``data/gels.json`` are
the capability and gel tables generated by the ha-godox-mesh project from the
Godox app's own catalogue; ``data/gel-colours.json`` is Godox's published gel
swatch list, which gives each gel its true colour. Built-in effect parameters
come from the library's ``FX_V3`` table.

The Godox mesh protocol is the same across the range; models differ only in
this metadata. So a light gets the right studio from data alone: look up its
``radioId``, and every tab, range and option follows from the row.
"""

from __future__ import annotations

import json
import logging
import re
import stat
from dataclasses import asdict, dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any, Literal

from godox_mesh_bt.protocol import FX_V3, FX_V3_DEFAULTS, FX_V3_SPEED_MAX

from .paths import PACKAGE_DATA

_CAPS_PATH = PACKAGE_DATA / "models.json"
#: Model files shipped with Gaffer: ``models/<driver>/<ID>.json``.
MODELS_DIR = Path(__file__).resolve().parent / "models"
logger = logging.getLogger(__name__)
_GELS_PATH = PACKAGE_DATA / "gels.json"
_CHIP_HEX_PATH = PACKAGE_DATA / "gel-colours.json"

#: The gel catalogue used to emulate gels on a light that has no gel mode.
EMULATION_GEL_VERSION = 2

Kind = Literal["rgb", "colour", "bicolour", "daylight", "unsupported"]

KIND_LABELS: dict[str, str] = {
    "rgb": "RGB + white",
    "colour": "Colour",
    "bicolour": "Bi-colour",
    "daylight": "Daylight",
    "unsupported": "Not supported",
}


@dataclass(frozen=True, slots=True)
class BuiltinEffect:
    symbol: int
    name: str
    params: tuple[dict[str, Any], ...]
    #: Highest speed the effect takes; 0 means one fixed speed.
    speed_max: int = 0


@dataclass(frozen=True, slots=True)
class ModelCaps:
    radio_id: str
    name: str
    chip: str
    min_kelvin: int
    max_kelvin: int
    gm_min: int
    gm_max: int
    modes: tuple[str, ...]
    effect_version: int
    effects: tuple[BuiltinEffect, ...]
    fan_modes: tuple[dict[str, Any], ...]
    color_chip_version: int
    rgb_display: int
    rgb_channels: tuple[str, ...]
    battery: bool
    smoothness_modes: tuple[dict[str, Any], ...] = field(default=())
    control_modes: tuple[dict[str, Any], ...] = field(default=())
    frequencies: tuple[dict[str, Any], ...] = field(default=())
    brightness_steps: int = 100
    note: str = ""
    known: bool = True
    #: Which driver commands this model (``drivers/<id>/``) and what to call its maker.
    driver: str = "godox"
    brand: str = "Godox"
    #: How an advertisement finds this model: ``{"name_prefix": str, "service": str}``, either optional.
    match: dict[str, Any] = field(default_factory=dict)
    #: Whatever the driver needs per model (opcodes, channel layout). Opaque to everything else.
    driver_data: dict[str, Any] = field(default_factory=dict)

    # -- what kind of light ---------------------------------------------------

    @property
    def has_white(self) -> bool:
        """A white (colour-temperature) mode, fixed or tunable."""
        return "cct" in self.modes and self.max_kelvin > 0

    @property
    def is_daylight(self) -> bool:
        """White at one fixed colour temperature: brightness is the only control."""
        return self.has_white and self.min_kelvin == self.max_kelvin

    @property
    def has_colour(self) -> bool:
        return "hsi" in self.modes

    @property
    def has_channels(self) -> bool:
        """Direct red/green/blue/white channel control."""
        return "rgb" in self.modes and "RGBW" in self.rgb_channels

    @property
    def has_tint(self) -> bool:
        return self.gm_min < 0 < self.gm_max

    @property
    def kind(self) -> Kind:
        if self.has_colour:
            return "rgb" if self.has_white else "colour"
        if self.has_white:
            return "daylight" if self.is_daylight else "bicolour"
        return "unsupported"

    @property
    def gel_support(self) -> str | None:
        """How gels reach this light: its own gel mode, recreated in colour, or as white."""
        if "color_chip" in self.modes and gels(self.color_chip_version):
            return "native"
        if self.has_colour:
            return "emulated"
        if self.has_white and (not self.is_daylight or self.has_tint):
            return "white"
        return None

    @property
    def effect_symbols(self) -> frozenset[int]:
        return frozenset(e.symbol for e in self.effects)

    @property
    def features(self) -> dict[str, Any]:
        """The switches the UI reads to decide which tabs and controls to show."""
        return {
            "white": self.has_white,
            "daylight": self.is_daylight,
            "colour": self.has_colour,
            "channels": self.has_channels,
            "tint": self.has_tint,
            "gels": self.gel_support,
            "builtin_effects": len(self.effects),
            "fan": bool(self.fan_modes),
            "battery": self.battery,
            "smoothness": bool(self.smoothness_modes),
            "control_modes": bool(self.control_modes),
        }

    def gel_table(self) -> tuple[dict[str, Any], ...]:
        """Every gel this light can show, each tagged with how it gets there."""
        from .gel_emulation import emulation_kind, fits_white_light

        support = self.gel_support
        if support is None:
            return ()
        if support == "native":
            return tuple({**g, "how": "native"} for g in gels(self.color_chip_version))
        if support == "emulated":
            return tuple({**g, "how": emulation_kind(g["hex"])} for g in gels(EMULATION_GEL_VERSION))
        return tuple({**g, "how": "white"} for g in gels(EMULATION_GEL_VERSION) if fits_white_light(g["hex"], self))

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data.update(
            has_tint=self.has_tint,
            kind=self.kind,
            kind_label=KIND_LABELS[self.kind],
            features=self.features,
        )
        return data


